import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import { spawn } from 'node:child_process';
import { pathToFileURL } from 'node:url';
import { createCodeFrame, parseStackFrame } from '../report/codeframe.js';

const DEFAULT_CRASHES_FILE = '.softscope/crashes.json';

/**
 * Loads recorded crashes from disk.
 */
export function loadCrashes(crashesPath = DEFAULT_CRASHES_FILE, projectRoot = process.cwd()) {
  const resolved = path.resolve(projectRoot, crashesPath);
  if (!fs.existsSync(resolved)) {
    return { crashes: [], filePath: resolved };
  }

  try {
    const raw = fs.readFileSync(resolved, 'utf-8');
    const data = JSON.parse(raw);
    const crashes = Array.isArray(data) ? data : (data.crashes || []);
    return { crashes, filePath: resolved };
  } catch {
    return { crashes: [], filePath: resolved };
  }
}

/**
 * Saves recorded crashes to disk.
 */
export function saveCrashes(crashes, crashesPath = DEFAULT_CRASHES_FILE, projectRoot = process.cwd()) {
  const resolved = path.resolve(projectRoot, crashesPath);
  fs.mkdirSync(path.dirname(resolved), { recursive: true });

  const payload = {
    version: 1,
    updatedAt: Date.now(),
    crashes
  };

  fs.writeFileSync(resolved, JSON.stringify(payload, null, 2), 'utf-8');
  return resolved;
}

/**
 * Records newly discovered unhandled crashes from auto-bench.
 */
export function recordDiscoveredCrashes(targetFile, fnResults, options = {}) {
  const projectRoot = options.projectRoot || process.cwd();
  const crashesFile = options.crashes || DEFAULT_CRASHES_FILE;
  const { crashes: existing } = loadCrashes(crashesFile, projectRoot);

  const newCrashes = [];
  const absTarget = path.resolve(projectRoot, targetFile);
  const relTarget = path.relative(projectRoot, absTarget);

  for (const fn of fnResults) {
    if (!fn.crashes || fn.crashes.length === 0) continue;

    for (const crash of fn.crashes) {
      const exportName = fn.exportName || fn.name;
      const crashArgs = crash.args !== undefined ? crash.args : (crash.seed !== undefined ? crash.seed : []);
      const id = `${relTarget}:${exportName}:${JSON.stringify(crashArgs)}`;

      newCrashes.push({
        id,
        targetFile: absTarget,
        relativePath: relTarget,
        functionName: fn.name,
        exportName,
        args: crashArgs,
        label: crash.label || '',
        error: crash.error,
        stack: crash.stack || '',
        line: crash.line || 1,
        column: crash.column || 1,
        status: 'unresolved',
        discoveredAt: Date.now()
      });
    }
  }

  if (newCrashes.length === 0) return 0;

  // Merge with existing, deduplicating by ID
  const map = new Map();
  for (const item of existing) {
    map.set(item.id, item);
  }
  for (const item of newCrashes) {
    map.set(item.id, item);
  }

  const merged = Array.from(map.values());
  const savedPath = saveCrashes(merged, crashesFile, projectRoot);
  const displayPath = path.relative(process.cwd(), savedPath) || savedPath;
  console.log(`[softscope] 💾 Recorded ${newCrashes.length} crash(es) to ${displayPath} (run 'softscope replay' to retest)`);
  return newCrashes.length;
}

/**
 * Generates standalone native node --test regression test code.
 */
export function generateRegressionTestSuite(crashes, projectRoot = process.cwd()) {
  if (!crashes || crashes.length === 0) {
    return '// No crashes recorded to generate regression tests from.\n';
  }

  // Group crashes by targetFile
  const byFile = new Map();
  for (const crash of crashes) {
    const list = byFile.get(crash.targetFile) || [];
    list.push(crash);
    byFile.set(crash.targetFile, list);
  }

  const lines = [
    `// Generated by Softscope Crash Replay at ${new Date().toISOString()}`,
    `import test from 'node:test';`,
    `import assert from 'node:assert/strict';`,
    ''
  ];

  const fileDefaultImports = new Map();
  let importCounter = 1;

  for (const [filePath, fileCrashes] of byFile.entries()) {
    const relImport = './' + path.relative(projectRoot, filePath).replace(/\\/g, '/');
    const exportsNeeded = Array.from(new Set(fileCrashes.map(c => c.exportName)));

    const namedImports = exportsNeeded.filter(e => e !== 'default');
    const hasDefault = exportsNeeded.includes('default');

    const importParts = [];
    if (hasDefault) {
      const defName = `defaultExport${importCounter}`;
      fileDefaultImports.set(filePath, defName);
      importParts.push(defName);
      importCounter++;
    }
    if (namedImports.length > 0) importParts.push(`{ ${namedImports.join(', ')} }`);

    lines.push(`import ${importParts.join(', ')} from ${JSON.stringify(relImport)};`);
  }

  lines.push('');

  for (const crash of crashes) {
    const fnCaller = crash.exportName === 'default'
      ? (fileDefaultImports.get(crash.targetFile) || 'defaultExport')
      : crash.exportName;
    const safeArgs = (crash.args || []).map(a => JSON.stringify(a)).join(', ');
    const testTitle = `Regression: ${crash.functionName}(${safeArgs}) handles input without throwing`;

    lines.push(`test(${JSON.stringify(testTitle)}, async () => {`);
    lines.push(`  assert.doesNotThrow(() => {`);
    lines.push(`    ${fnCaller}(${safeArgs});`);
    lines.push(`  });`);
    lines.push(`});`);
    lines.push('');
  }

  return lines.join('\n');
}

/**
 * Executes softscope replay.
 */
export async function runReplay(options = {}) {
  const projectRoot = options.projectRoot || process.cwd();
  const crashesFile = options.crashes || DEFAULT_CRASHES_FILE;
  const targetFilterFile = options.command && options.command[1] ? path.resolve(projectRoot, options.command[1]) : null;

  // Handle --clear
  if (options.clear) {
    const resolved = path.resolve(projectRoot, crashesFile);
    if (fs.existsSync(resolved)) {
      fs.unlinkSync(resolved);
    }
    console.log(`[softscope] 🧹 Cleared recorded crashes from ${path.relative(process.cwd(), resolved) || resolved}`);
    return 0;
  }

  const { crashes, filePath: resolvedCrashesPath } = loadCrashes(crashesFile, projectRoot);

  if (crashes.length === 0) {
    console.log(`[softscope] ✔ No recorded crashes found in ${path.relative(process.cwd(), resolvedCrashesPath) || resolvedCrashesPath}`);
    console.log(`Tip: Run 'softscope auto-bench <file>' with fuzzing enabled to discover edge-case crashes.`);
    return 0;
  }

  // Filter crashes
  let filtered = [...crashes];
  if (targetFilterFile) {
    filtered = filtered.filter(c => path.resolve(c.targetFile) === targetFilterFile);
  }
  if (options.filter) {
    const fnRegex = new RegExp(options.filter.replace(/\*/g, '.*'), 'i');
    filtered = filtered.filter(c => fnRegex.test(c.functionName) || fnRegex.test(c.exportName));
  }

  if (filtered.length === 0) {
    console.log(`[softscope] No matching recorded crashes for the specified filter.`);
    return 0;
  }

  // Handle --test / --generate-test
  if (options.testSuite) {
    const suiteCode = generateRegressionTestSuite(filtered, projectRoot);
    if (options.output) {
      const outPath = path.resolve(projectRoot, options.output);
      fs.mkdirSync(path.dirname(outPath), { recursive: true });
      fs.writeFileSync(outPath, suiteCode, 'utf-8');
      console.log(`[softscope] 📝 Generated regression test suite written to ${path.relative(process.cwd(), outPath) || outPath}`);
    } else {
      process.stdout.write(suiteCode);
    }
    return 0;
  }

  console.log(`\n\x1b[1;36mSoftscope Crash Replay\x1b[0m`);
  console.log(`\x1b[90m───────────────────────────────────────────────────────────\x1b[0m`);
  console.log(`Replaying \x1b[1m${filtered.length}\x1b[0m recorded crash test case(s)...\n`);

  let resolvedCount = 0;
  let failingCount = 0;
  const remainingCrashes = [];

  // Replay each crash
  for (const crash of filtered) {
    const result = await executeReplayCase(crash, projectRoot);

    const safeArgs = (crash.args || []).map(a => JSON.stringify(a)).join(', ');
    const callSignature = `${crash.functionName}(${safeArgs})`;

    if (result.resolved) {
      resolvedCount++;
      console.log(`  \x1b[1;32m✔\x1b[0m \x1b[1m${callSignature}\x1b[0m`);
      console.log(`    \x1b[32mRESOLVED 🎉\x1b[0m (Returned: ${result.returnValue !== undefined ? JSON.stringify(result.returnValue) : 'void'})`);
      console.log(`    \x1b[90mLocation: ${crash.relativePath}:${crash.line}:${crash.column}\x1b[0m\n`);
    } else {
      failingCount++;
      remainingCrashes.push(crash);
      console.log(`  \x1b[1;31m✖\x1b[0m \x1b[1m${callSignature}\x1b[0m`);
      console.log(`    \x1b[31mSTILL FAILING:\x1b[0m ${result.error}`);
      if (crash.targetFile && fs.existsSync(crash.targetFile)) {
        const frame = createCodeFrame(crash.targetFile, crash.line, crash.column, {
          message: result.error,
          color: true
        });
        if (frame) {
          console.log(frame + '\n');
        }
      }
    }
  }

  // Update crashes.json by removing resolved crashes from the active set
  const unresolvedMap = new Map(remainingCrashes.map(c => [c.id, c]));
  const updatedAll = crashes.filter(c => {
    // If it was in filtered and got resolved, omit it
    const wasInFiltered = filtered.some(f => f.id === c.id);
    if (wasInFiltered) {
      return unresolvedMap.has(c.id);
    }
    return true; // Keep crashes from other files
  });

  saveCrashes(updatedAll, crashesFile, projectRoot);

  console.log(`\x1b[90m───────────────────────────────────────────────────────────\x1b[0m`);
  console.log(`Replay Summary: \x1b[32m${resolvedCount} resolved\x1b[0m, \x1b[31m${failingCount} still failing\x1b[0m\n`);

  if (failingCount > 0) {
    return 1;
  }

  console.log(`[softscope] 🎉 All replayed crashes have been resolved!\n`);
  return 0;
}

/**
 * Executes a single crash case in an isolated child process to ensure safety.
 */
async function executeReplayCase(crash, projectRoot) {
  const runner = findRunner(crash.targetFile, projectRoot);
  const targetUrl = pathToFileURL(crash.targetFile).href;
  const tmpRunner = path.join(os.tmpdir(), `softscope-replay-${Date.now()}-${Math.random().toString(36).slice(2)}.mjs`);

  const code = `
import { pathToFileURL } from 'node:url';

async function run() {
  let mod;
  try {
    mod = await import(${JSON.stringify(targetUrl)});
  } catch (err) {
    process.stdout.write(JSON.stringify({
      resolved: false,
      error: 'Import error: ' + err.message,
      stack: err.stack
    }));
    return;
  }

  const exportName = ${JSON.stringify(crash.exportName)};
  const fn = mod[exportName] || (exportName === 'default' ? mod.default : null);

  if (typeof fn !== 'function') {
    process.stdout.write(JSON.stringify({
      resolved: false,
      error: 'Target export is not a function: ' + exportName
    }));
    return;
  }

  const args = ${JSON.stringify(crash.args)};
  try {
    let ret;
    try {
      ret = fn(...args);
    } catch (err) {
      if (err instanceof TypeError && err.message && err.message.includes("cannot be invoked without 'new'")) {
        ret = new fn(...args);
      } else {
        throw err;
      }
    }

    if (ret && typeof ret.then === 'function') {
      ret = await ret;
    }

    process.stdout.write(JSON.stringify({
      resolved: true,
      returnValue: typeof ret === 'function' ? '[Function]' : ret
    }));
  } catch (err) {
    process.stdout.write(JSON.stringify({
      resolved: false,
      error: err ? (err.message || String(err)) : 'Unknown error',
      stack: err ? err.stack : ''
    }));
  }
}

run();
`;

  try {
    fs.writeFileSync(tmpRunner, code, 'utf-8');

    const cleanEnv = { ...process.env };
    delete cleanEnv.NODE_OPTIONS;
    delete cleanEnv.SOFTSCOPE_SESSION_DIR;
    delete cleanEnv.SOFTSCOPE_CONFIG;
    delete cleanEnv.SOFTSCOPE_LIVE;
    delete cleanEnv.SOFTSCOPE_CAPTURE_SEEDS;
    delete cleanEnv.SOFTSCOPE_IPC_SOCKET;

    const res = await new Promise((resolve) => {
      const child = spawn(runner.executable, [...runner.args, tmpRunner], {
        cwd: projectRoot,
        env: cleanEnv,
        stdio: ['ignore', 'pipe', 'pipe']
      });

      let stdout = '';
      let stderr = '';

      child.stdout.on('data', chunk => { stdout += chunk.toString('utf-8'); });
      child.stderr.on('data', chunk => { stderr += chunk.toString('utf-8'); });

      child.on('close', code => {
        resolve({ code, stdout, stderr });
      });

      child.on('error', err => {
        resolve({ code: 1, stdout: '', stderr: err.message });
      });
    });

    if (res.stdout) {
      try {
        return JSON.parse(res.stdout);
      } catch {
        return { resolved: false, error: res.stdout || res.stderr || 'Execution failed' };
      }
    }

    return { resolved: false, error: res.stderr || `Exited with code ${res.code}` };
  } finally {
    try {
      if (fs.existsSync(tmpRunner)) fs.unlinkSync(tmpRunner);
    } catch {
      // Ignore cleanup error
    }
  }
}

function findRunner(targetFile, projectRoot) {
  let currentDir = path.dirname(targetFile);
  const root = path.parse(currentDir).root;
  while (currentDir && currentDir !== root) {
    const candidate = path.join(currentDir, 'node_modules', '.bin', 'tsx');
    if (fs.existsSync(candidate)) {
      return { executable: candidate, args: [] };
    }
    currentDir = path.dirname(currentDir);
  }

  const rootCandidate = path.join(projectRoot || process.cwd(), 'node_modules', '.bin', 'tsx');
  if (fs.existsSync(rootCandidate)) {
    return { executable: rootCandidate, args: [] };
  }

  return {
    executable: process.execPath,
    args: []
  };
}
